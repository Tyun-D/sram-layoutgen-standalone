@dataclass(frozen=True)
class Bounds:
    x0: float
    y0: float
    x1: float
    y1: float

    @property
    def width(self) -> float:
        return self.x1 - self.x0

    @property
    def height(self) -> float:
        return self.y1 - self.y0

    @property
    def center(self) -> tuple[float, float]:
        return ((self.x0 + self.x1) / 2.0, (self.y0 + self.y1) / 2.0)

    def to_rect(self) -> dict[str, float]:
        return {
            "x0": round(self.x0, 6),
            "y0": round(self.y0, 6),
            "x1": round(self.x1, 6),
            "y1": round(self.y1, 6),
            "width": round(self.width, 6),
            "height": round(self.height, 6),
        }


def _json_dump(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _write_csv(path: Path, fieldnames: list[str], rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def _read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _md_table(columns: list[str], rows: list[dict[str, Any]]) -> str:
    lines = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join(["---"] * len(columns)) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(str(row.get(column, "")).replace("\n", "<br>") for column in columns) + " |")
    return "\n".join(lines) + "\n"


def _normalize_name(name: str) -> str:
    return name.strip().lower().replace(" ", "_")


def _pin_rect_to_bounds(rect: dict[str, Any]) -> Bounds:
    return Bounds(float(rect["x0"]), float(rect["y0"]), float(rect["x1"]), float(rect["y1"]))


def _row_bounds(row: dict[str, Any]) -> Bounds:
    rect = row["rect"]
    return Bounds(float(rect["x0"]), float(rect["y0"]), float(rect["x1"]), float(rect["y1"]))


def _merge_bounds(bounds_list: list[Bounds]) -> Bounds:
    if not bounds_list:
        raise ValueError("bounds_list must not be empty")
    return Bounds(
        min(item.x0 for item in bounds_list),
        min(item.y0 for item in bounds_list),
        max(item.x1 for item in bounds_list),
        max(item.y1 for item in bounds_list),
    )


def _role_index(layout_json: dict[str, Any]) -> tuple[dict[str, list[dict[str, Any]]], dict[str, Bounds], Bounds]:
    role_rows: dict[str, list[dict[str, Any]]] = {}
    all_bounds: list[Bounds] = []
    for collection_name in ("cell_arrays", "instances"):
        for row in layout_json[collection_name]:
            role = row.get("role", "")
            if not role:
                continue
            role_rows.setdefault(role, []).append(row)
            all_bounds.append(_row_bounds(row))
    role_bounds = {role: _merge_bounds([_row_bounds(row) for row in rows]) for role, rows in role_rows.items()}
    if not all_bounds:
        raise ValueError("No layout roles found in M2R layout json.")
    top_bounds = _merge_bounds(all_bounds)
    return role_rows, role_bounds, top_bounds


def _label_anchor(index: int, bounds: Bounds) -> tuple[float, float]:
    x = bounds.x0 + 0.25 + 0.25 * (index % 4)
    y = bounds.y1 - 0.45 - 0.35 * (index // 4)
    return (round(x, 6), round(max(bounds.y0 + 0.2, y), 6))


def _gds_sanity(gds_path: Path, top_cell_name: str) -> dict[str, Any]:
    try:
        lib = gdstk.read_gds(gds_path)
    except Exception as exc:
        return {
            "status": "GDS_PARSE_FAILED",
            "error": str(exc),
            "top_cell_name": None,
            "gds_size_bytes": gds_path.stat().st_size if gds_path.exists() else 0,
        }
    tops = lib.top_level()
    top = next((cell for cell in tops if cell.name == top_cell_name), tops[0] if tops else None)
    if top is None:
        return {
            "status": "TOP_CELL_MISSING",
            "error": "Top cell not found.",
            "top_cell_name": None,
            "gds_size_bytes": gds_path.stat().st_size,
        }
    bbox = top.bounding_box()
    top_bbox = None
    if bbox is not None:
        top_bbox = {
            "x0": round(float(bbox[0][0]), 6),
            "y0": round(float(bbox[0][1]), 6),
            "x1": round(float(bbox[1][0]), 6),
            "y1": round(float(bbox[1][1]), 6),
            "width": round(float(bbox[1][0] - bbox[0][0]), 6),
            "height": round(float(bbox[1][1] - bbox[0][1]), 6),
        }
    return {
        "status": "GDS_PARSED_SANITY_PASSED",
        "error": "",
        "top_cell_name": str(top.name),
        "gds_size_bytes": gds_path.stat().st_size,
        "cell_count": len(lib.cells),
        "top_bbox": top_bbox,
    }


def _find_cell(lib: gdstk.Library, name: str) -> gdstk.Cell | None:
    for cell in lib.cells:
        if cell.name == name:
            return cell
    return None


def _pick_pin(layout_pins: list[dict[str, Any]], binding_row: dict[str, str]) -> tuple[dict[str, Any] | None, str]:
    target_pin = binding_row["openyield_target_pin"]
    source_pin = binding_row["openyield_source_pin"]
    net_name = binding_row["net_name"]
    candidates = [target_pin, source_pin, net_name]
    normalized_layout_pins = {_normalize_name(item["name"]): item for item in layout_pins}
    normalized_layout_nets = {_normalize_name(item["net"]): item for item in layout_pins}

    def aliases(token: str) -> list[str]:
        token = token.strip()
        values = [token]
        if token in PIN_ALIAS_MAP:
            values.append(PIN_ALIAS_MAP[token])
        lowered = token.lower()
        if lowered in PIN_ALIAS_MAP:
            values.append(PIN_ALIAS_MAP[lowered])
        if "[i]" in token:
            values.extend(
                [
                    token.replace("[i]", "[0]"),
                    token.replace("[i]", "[*]"),
                ]
            )
        if "[*]" in token:
            values.append(token.replace("[*]", "[0]"))
        if ";" in token:
            values.extend(part.strip() for part in token.split(";"))
        if "/" in token:
            values.extend(part.strip() for part in token.split("/"))
        return values

    for candidate in candidates:
        for alias in aliases(candidate):
            key = _normalize_name(alias)
            if key in normalized_layout_pins:
                return normalized_layout_pins[key], f"top_pin:{alias}"
            if key in normalized_layout_nets:
                return normalized_layout_nets[key], f"top_net:{alias}"
    return None, "region_fallback"


